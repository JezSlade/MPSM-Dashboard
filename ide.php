function list_files($dir, $base = '') {
    if (!is_dir($dir)) return [];
    $items = [];
    foreach (scandir($dir) as $item) {
        if ($item === '.' || $item === '..') continue;
        $path = "$dir/$item";
        $rel = ltrim("$base/$item", '/');
        if (is_dir($path)) {
            $items[] = ["type"=>"dir","name"=>$item,"path"=>$rel,"children"=>list_files($path,$rel)];
        } else {
            $size = filesize($path);
            $ext = pathinfo($item, PATHINFO_EXTENSION);
            $items[] = ["type"=>"file","name"=>$item." (".($ext?:'unknown')." - ".number_format($size/1024,1)."KB)","path"=>$rel];
        }
    }
    usort($items, fn($a,$b)=>strcasecmp($a['name'],$b['name']));
    return $items;
}

function backup_file($file_path) {
    global $today_backup_dir;
    $rel = str_replace(IDE_ROOT, '', $file_path);
    $backup_dir = $today_backup_dir . '/' . dirname(ltrim($rel, '/'));
    if (!is_dir($backup_dir)) mkdir($backup_dir, 0755, true);
    $timestamp = date('His');
    $backup_file = $backup_dir . '/' . basename($file_path) . ".bak_$timestamp";
    return copy($file_path, $backup_file);
}

function create_new_widget($name) {
    $safe = preg_replace('/[^a-zA-Z0-9_]/', '_', $name);
    $file = IDE_ROOT . "/$safe.php";
    if (file_exists($file)) return false;
    $template = "<?php\n";
    $template .= "/**\n * Widget: $safe\n * Auto-generated by IDE\n */\n\n";
    $template .= "function render_".$safe."_widget() {\n";
    $template .= "    echo '<div class=\\"widget\\">".$safe." widget content here</div>';\n";
    $template .= "}\n";
    return file_put_contents($file, $template) !== false;
}

